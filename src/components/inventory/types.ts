/** Shape of a stock document as returned by /api/inventory/docs/:id (see lib/inventory.ts). */
export interface StockLine {
  id: string;
  item: string;
  itemName: string;
  sku?: string;
  unit?: string;
  purchaseUnit?: string;
  conversion?: number;
  batch?: string;
  batchNo?: string;
  expiryDate?: string;
  qty: number;
  freeQty?: number;
  receivedQty?: number;
  returnedQty?: number;
  rate: number;
  mrp?: number;
  discountPct?: number;
  gstRate?: number;
  taxable?: number;
  gst?: number;
  amount?: number;
  systemQty?: number;
  countedQty?: number;
  remarks?: string;
}

