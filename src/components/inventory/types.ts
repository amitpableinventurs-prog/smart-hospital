  type: string;
  code: string;
  docDate: string;
  status: string;
  store?: string;
  storeName?: string;
  toStore?: string;
  toStoreName?: string;
  department?: string;
  supplier?: string;
  supplierName?: string;
  patient?: string;
  patientName?: string;
  patientCode?: string;
  admissionCode?: string;
  requisition?: string;
  requisitionCode?: string;
  po?: string;
  poCode?: string;
  against?: string;
  againstCode?: string;
  againstType?: string;
  reservation?: string;
  reservationCode?: string;
  purpose?: string;
  reason?: string;
  priority?: string;
  invoiceNo?: string;
  invoiceDate?: string;
  dueDate?: string;
  requiredBy?: string;
  expectedDate?: string;
  terms?: string;
  notes?: string;
  lines: StockLine[];
  taxableTotal: number;
  gstTotal: number;
  roundOff: number;
  netAmount: number;
  costValue: number;
  chargeToPatient?: boolean;
  billingInvoiceCode?: string;
  approvedAt?: string;
  approvedByName?: string;
  postedAt?: string;
  postedByName?: string;
  cancelledAt?: string;
